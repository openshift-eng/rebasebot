"""Markdown rendering for rebase pull request bodies."""

from __future__ import annotations

import re
import shlex

from rebasebot.github import GitHubBranch
from rebasebot.prow import ProwJobContext
from rebasebot.rebase_summary import ContentLossWarning, RebaseSummary

PR_BODY_LOST_LINE_LIMIT = 20
DROPPED_COMMITS_DISPLAY_LIMIT = 20


def _branch_link(branch: GitHubBranch) -> str:
    label = re.sub(r"([\\`*_\[\]<>])", r"\\\1", branch.label)
    return f"[{label}]({branch.web_url})"


def build_merge_pr_body(
    source: GitHubBranch,
    dest: GitHubBranch,
    rebase: GitHubBranch,
    prow_job: ProwJobContext,
    *,
    conflicted_pr_number: int | None = None,
) -> str:
    """Describe an upstream sync PR and optional manual conflict resolution."""
    repo = shlex.quote(f"{dest.ns}/{dest.name}")
    body = f"This PR syncs upstream changes from {_branch_link(source)} into {_branch_link(dest)}."
    if conflicted_pr_number is not None:
        dest_ssh = shlex.quote(f"git@github.com:{dest.ns}/{dest.name}.git")
        rebase_ssh = shlex.quote(f"git@github.com:{rebase.ns}/{rebase.name}.git")
        pause_updates = f"gh pr edit {conflicted_pr_number} --repo {repo} --add-label rebase/manual &&\n"
        checkout_pr = f"gh pr checkout {conflicted_pr_number} --repo {repo} --detach &&\n"
        merge_dest = (
            f"git fetch --no-tags -- {dest_ssh} {shlex.quote(f'refs/heads/{dest.branch}')} &&\n"
            "git merge --no-ff --no-edit --no-squash --no-commit FETCH_HEAD\n"
        )
        body += (
            "\n\n## Resolve conflicts\n\n"
            "Conflict detected. Resolve manually. Keep `rebase/manual` until this PR is merged.\n\n"
            f"Go to your local clone of `{dest.ns}/{dest.name}`, then run:\n\n"
            "**Reuse your checkout.** Start with a clean working tree.\n\n"
            "```sh\n"
            f"{pause_updates}"
            'test -z "$(git status --porcelain --untracked-files=all)" &&\n'
            f"{checkout_pr}"
            f"{merge_dest}"
            "```\n\n"
            "<details>\n<summary>Use a temporary worktree instead</summary>\n\n"
            "```sh\n"
            f"{pause_updates}"
            f'workdir=$(mktemp -d "${{TMPDIR:-/tmp}}/rebasebot-pr-{conflicted_pr_number}.XXXXXX") &&\n'
            'git worktree add --detach "$workdir" HEAD &&\n'
            'cd "$workdir" &&\n'
            f"{checkout_pr}"
            f"{merge_dest}"
            "```\n\n</details>\n\n"
            "Resolve the conflicts, then stage the resolved files and any other intended changes. "
            "Review the staged diff, then run:\n\n"
            "```sh\n"
            "git diff --cached --check &&\n"
            "git commit --no-edit &&\n"
            f"git push --no-follow-tags -- {rebase_ssh} {shlex.quote(f'HEAD:refs/heads/{rebase.branch}')}\n"
            "```"
        )
    if prow_job.log_url is not None:
        body += f"\n\n[View job log]({prow_job.log_url})"
    return body


def build_pr_body(
    summary: RebaseSummary,
    source: GitHubBranch,
    dest: GitHubBranch,
    prow_job: ProwJobContext,
) -> str:
    """Render the Markdown body for a rebase pull request."""
    sections: list[str] = [
        "This is an automated rebase PR generated by RebaseBot.",
    ]

    if summary.upstream_commit_count == 1:
        commit_line = "1 new upstream commit"
    else:
        commit_line = f"{summary.upstream_commit_count} new upstream commits"

    summary_lines = [
        f"- **Source**: {_branch_link(source)}",
        f"- **Destination**: {_branch_link(dest)}",
        f"- **{commit_line}**",
    ]
    sections.append("## Summary\n" + "\n".join(summary_lines))

    if summary.dropped_commits:
        dropped_lines = [
            f"- `{commit.sha[:7]}` {commit.message} ({commit.reason})"
            for commit in summary.dropped_commits[:DROPPED_COMMITS_DISPLAY_LIMIT]
        ]
        remaining = len(summary.dropped_commits) - DROPPED_COMMITS_DISPLAY_LIMIT
        if remaining > 0:
            dropped_lines.append(f"- ... and {remaining} more")
        sections.append("## Dropped downstream commits\n" + "\n".join(dropped_lines))

    if summary.art_pr is not None:
        sections.append(
            "## ART pull request cherry-picked\n\n"
            f"[#{summary.art_pr.number} {summary.art_pr.title}]({summary.art_pr.url})"
        )

    if summary.content_loss_warnings:
        warnings_by_commit: dict[tuple[str, str], list[ContentLossWarning]] = {}
        commit_order: list[tuple[str, str]] = []
        for warning in summary.content_loss_warnings:
            key = (warning.sha, warning.message)
            if key not in warnings_by_commit:
                warnings_by_commit[key] = []
                commit_order.append(key)
            warnings_by_commit[key].append(warning)

        details_blocks: list[str] = []
        for key in commit_order:
            sha, message = key
            file_sections: list[str] = []
            for warning in warnings_by_commit[key]:
                displayed_lines = warning.lost_lines[:PR_BODY_LOST_LINE_LIMIT]
                code_block = "\n".join(line.strip() for line in displayed_lines)
                file_section = f"**{warning.file}**\n```\n{code_block}\n```"
                remaining = len(warning.lost_lines) - PR_BODY_LOST_LINE_LIMIT
                if remaining > 0:
                    file_section += f"\n... and {remaining} more lines"
                file_sections.append(file_section)

            details_blocks.append(
                f"<details>\n<summary>`{sha[:7]}` {message}</summary>\n\n"
                + "\n\n".join(file_sections)
                + "\n\n</details>"
            )

        sections.append("## ⚠️ Possible upstream content loss\n\n" + "\n\n".join(details_blocks))

    if prow_job.log_url is not None:
        sections.append(f"## Logs\n\n[View job log]({prow_job.log_url})")

    return "\n\n".join(sections)
